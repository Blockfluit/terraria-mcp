    internal static (ArrayTileGrid Grid, TilePoint Start) Shaft()
    {
        var rows = ShaftTop.ToList();
        for (int y = rows.Count; y <= 45; y++) rows.Add("????????????#####..########");
        rows.Add("????????????##########?????");
        rows.Add("????????????##########?????");
        var (g, m) = ArrayTileGrid.Parse(rows.ToArray());
        return (g, m['S']);
    }

    private static MovementProfile Real(int pick = 0, int builds = 0) =>
        JumpModel.Apply(new MovementProfile(PickPower: pick, BuildItemCount: builds), PlayerPhysics.Vanilla);

    private static readonly TilePoint Floor = new(17, 45);

    /// <summary>No ledge fits the 3-tall body and the drop is 29 tiles (safe: 20), so move_to's default plan digs a
    /// staircase down the left wall and takes only safe falls.</summary>
    [Fact]
    public void DescendsToTheFloor_WithSafeFallsOnly()
    {
        var (g, s) = Shaft();
        var profile = Real(pick: 35, builds: 163);
        var r = Pathfinder.FindPath(g, s, Floor, profile, new(AllowBuild: false));
        output.WriteLine($"{r.Success} {r.FailureReason} " + string.Join(" ", r.Steps.Select(st => $"{st.Kind}{st.Pos}{st.WorkTile}")));
        Assert.True(r.Success, r.FailureReason);
        Assert.Equal(Floor, r.Steps[^1].Pos);
        var prev = s;
        foreach (var st in r.Steps)
        {
            Assert.True(st.Pos.Y - prev.Y <= profile.SafeFallTiles, $"unsafe drop {prev} -> {st.Pos}");
            prev = st.Pos;
        }

        // ...and the follower executes it in the sim, unhurt.
        var sim = new Sim.MiniPhysics(g, s) { PickPower = 35 };
        var f = new PathFollower(r.Steps, start: s);
        FollowerOutput o = default;
        for (int t = 0; t < 6000 && (o = f.Tick(sim.Kinematics, g)).Status == FollowerStatus.Running; t++)
            sim.Step(o.Intent, o.Current?.Kind == MoveKind.Dig ? Sim.SimTool.Pickaxe : Sim.SimTool.None);
        output.WriteLine($"{o.Status} {sim}");
        Assert.Equal(FollowerStatus.Arrived, o.Status);
        Assert.Null(sim.Hurt);
        Assert.Equal(Floor, sim.StandingTile);
    }

    [Fact]
    public void WithBuildingAllowed_StillReachesTheFloor()
    {
        var (g, s) = Shaft();
        var r = Pathfinder.FindPath(g, s, Floor, Real(pick: 35, builds: 163), new());
        Assert.True(r.Success, r.FailureReason);
        Assert.Equal(Floor, r.Steps[^1].Pos);
    }
}
