{
    /// <summary>The shaft seen in game (origin x=4244 y=585): the player on a ledge at (16,16) = (4260,601); below it
    /// a 2–3 wide shaft whose left wall has 2-tall notches, continuing to a floor at row 46 (y=631).</summary>
    internal static readonly string[] ShaftTop =
    {
